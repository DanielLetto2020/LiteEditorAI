// LiteEditorAI — нормализация текста перед синтезом речи (модуль «Озвучка»).
//
// Зачем это нужно (проверено на живом движке 2026-08-31):
//   1. Silero v4_ru **не разворачивает числа**: «Обработано 15 файлов» звучит короче, чем
//      «Обработано пятнадцать файлов» — цифры просто проглатываются.
//   2. Фраза **без единой кириллической буквы роняет движок** с пустым `ValueError`:
//      «1.1.192», «LiteEditor build ok», «(1)», «— …» — всё это падало, а вместе с фразой
//      обрывалось и чтение всего текста.
// Поэтому перед синтезом числа разворачиваются словами, латиница читается по-русски, а фразу,
// в которой после этого нечего произносить, вызывающая сторона просто пропускает (hasSpeakable).
//
// Падежи существительных после числительных не согласуются (кроме процентов и единиц измерения):
// это потребовало бы морфологии, а на слух «пятнадцать файлов» и так разборчиво.

const ONES = ['ноль', 'один', 'два', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять',
  'десять', 'одиннадцать', 'двенадцать', 'тринадцать', 'четырнадцать', 'пятнадцать',
  'шестнадцать', 'семнадцать', 'восемнадцать', 'девятнадцать'];
const ONES_F = ONES.slice();
ONES_F[1] = 'одна'; ONES_F[2] = 'две';   // тысяча — женского рода: «двадцать одна тысяча»
const TENS = ['', '', 'двадцать', 'тридцать', 'сорок', 'пятьдесят', 'шестьдесят', 'семьдесят', 'восемьдесят', 'девяносто'];
const HUNDREDS = ['', 'сто', 'двести', 'триста', 'четыреста', 'пятьсот', 'шестьсот', 'семьсот', 'восемьсот', 'девятьсот'];
// разряды: [единственное, 2–4, много, женский ли род разряда]
const SCALES = [
  ['', '', '', false],
  ['тысяча', 'тысячи', 'тысяч', true],
  ['миллион', 'миллиона', 'миллионов', false],
  ['миллиард', 'миллиарда', 'миллиардов', false],
  ['триллион', 'триллиона', 'триллионов', false],
];

// Русская форма по числу: 1 файл / 2 файла / 5 файлов.
function plural(n, one, few, many) {
  const a = Math.abs(n) % 100, b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b > 1 && b < 5) return few;
  if (b === 1) return one;
  return many;
}

// Группа 0–999 словами.
function group3(n, feminine) {
  const words = [];
  const h = Math.floor(n / 100), rest = n % 100;
  if (h) words.push(HUNDREDS[h]);
  const ones = feminine ? ONES_F : ONES;
  if (rest < 20) { if (rest) words.push(ones[rest]); }
  else {
    words.push(TENS[Math.floor(rest / 10)]);
    if (rest % 10) words.push(ones[rest % 10]);
  }
  return words.join(' ');
}

// Целое число словами. Работает до триллионов; всё, что длиннее, читается по цифрам —
// это всё равно не число, а идентификатор.
function numberToWords(value, feminine = false) {
  let n = typeof value === 'number' ? value : parseInt(String(value), 10);
  if (!Number.isFinite(n)) return String(value);
  if (n === 0) return 'ноль';
  const out = [];
  if (n < 0) { out.push('минус'); n = -n; }
  if (n >= 1e15) return String(value).split('').map((d) => (/\d/.test(d) ? ONES[+d] : d)).join(' ');
  const groups = [];
  while (n > 0) { groups.push(n % 1000); n = Math.floor(n / 1000); }
  for (let i = groups.length - 1; i >= 0; i--) {
    const g = groups[i];
    if (!g) continue;
    const [one, few, many, fem] = SCALES[i];
    out.push(group3(g, i === 0 ? feminine : fem));
    if (one) out.push(plural(g, one, few, many));
  }
  return out.join(' ');
}

// Латиница Silero не читает вовсе, поэтому переводим её в кириллицу. Порядок важен: сначала
// диграфы, потом одиночные буквы.
const DIGRAPHS = [
  ['sch', 'ш'], ['sh', 'ш'], ['ch', 'ч'], ['ph', 'ф'], ['th', 'т'], ['ck', 'к'],
  ['ee', 'и'], ['oo', 'у'], ['ea', 'и'], ['ou', 'ау'], ['qu', 'кв'], ['ya', 'я'],
  ['yu', 'ю'], ['ts', 'ц'], ['zh', 'ж'], ['kh', 'х'], ['ay', 'эй'], ['ey', 'ей'],
];
const LETTERS = {
  a: 'а', b: 'б', c: 'к', d: 'д', e: 'е', f: 'ф', g: 'г', h: 'х', i: 'и', j: 'дж',
  k: 'к', l: 'л', m: 'м', n: 'н', o: 'о', p: 'п', q: 'к', r: 'р', s: 'с', t: 'т',
  u: 'у', v: 'в', w: 'в', x: 'кс', y: 'й', z: 'з',
};
// Названия латинских букв — для аббревиатур, которые читают по буквам (JS → «джей эс»).
const LETTER_NAMES = {
  a: 'эй', b: 'би', c: 'си', d: 'ди', e: 'и', f: 'эф', g: 'джи', h: 'эйч', i: 'ай',
  j: 'джей', k: 'кей', l: 'эль', m: 'эм', n: 'эн', o: 'оу', p: 'пи', q: 'кью', r: 'ар',
  s: 'эс', t: 'ти', u: 'ю', v: 'ви', w: 'дабл ю', x: 'икс', y: 'вай', z: 'зед',
};
// Частые в выводе агента и терминала слова: транслитерация читается смешно, а звучат они постоянно.
const TERMS = {
  ok: 'окей', error: 'ошибка', warning: 'предупреждение', failed: 'ошибка', done: 'готово',
  git: 'гит', commit: 'коммит', push: 'пуш', pull: 'пул', merge: 'мёрдж', branch: 'ветка',
  build: 'билд', test: 'тест', tests: 'тесты', file: 'файл', files: 'файлы', line: 'строка',
  npm: 'эн пи эм', node: 'ноуд', python: 'пайтон', json: 'джейсон', yaml: 'ямл', js: 'джей эс',
  ts: 'ти эс', css: 'си эс эс', html: 'эйч ти эм эль', sql: 'эс кью эль', api: 'эй пи ай',
  url: 'юр эл', http: 'эйч ти ти пи', https: 'эйч ти ти пи эс', id: 'ай ди', ui: 'ю ай',
  linux: 'линукс', docker: 'докер', podman: 'подман', bash: 'баш', shell: 'шелл',
  true: 'тру', false: 'фолс', null: 'налл', undefined: 'андефайнд',
};
const UNITS = {
  'КБ': ['килобайт', 'килобайта', 'килобайт'], 'МБ': ['мегабайт', 'мегабайта', 'мегабайт'],
  'ГБ': ['гигабайт', 'гигабайта', 'гигабайт'], 'ТБ': ['терабайт', 'терабайта', 'терабайт'],
  'мс': ['миллисекунда', 'миллисекунды', 'миллисекунд'], 'сек': ['секунда', 'секунды', 'секунд'],
  'мин': ['минута', 'минуты', 'минут'], 'ч': ['час', 'часа', 'часов'],
  'км': ['километр', 'километра', 'километров'], 'кг': ['килограмм', 'килограмма', 'килограммов'],
};
/** @type {[RegExp, string][]} */
const SYMBOLS = [
  [/№\s*(?=\d)/g, 'номер '],
  [/&/g, ' и '],
  [/±/g, ' плюс минус '],
  [/×/g, ' на '],
  [/°C/g, ' градусов Цельсия'],
  // Знак валюты стоит ПЕРЕД числом, а произносится после него: «$100» — «сто долларов».
  [/\$\s*(\d+(?:[ .,]\d+)*)/g, '$1 долларов '],
  [/€\s*(\d+(?:[ .,]\d+)*)/g, '$1 евро '],
  [/₽\s*(\d+(?:[ .,]\d+)*)/g, '$1 рублей '],
  [/(\d)\s*₽/g, '$1 рублей'], [/(\d)\s*\$/g, '$1 долларов'], [/(\d)\s*€/g, '$1 евро'],
];

const CYRILLIC = /[а-яёА-ЯЁ]/;

function translitWord(w) {
  const lower = w.toLowerCase();
  if (TERMS[lower]) return TERMS[lower];
  // Аббревиатура (BUILD, JS, HTTP) — читаем по буквам, транслит из них получается бессмысленным.
  if (w.length <= 5 && w === w.toUpperCase() && /^[A-Z]+$/.test(w)) {
    return w.toLowerCase().split('').map((c) => LETTER_NAMES[c] || c).join(' ');
  }
  let s = lower;
  for (const [from, to] of DIGRAPHS) s = s.split(from).join(to);
  return s.split('').map((c) => (LETTERS[c] !== undefined ? LETTERS[c] : c)).join('');
}

// Главная функция: текст → текст, который движок прочитает вслух.
function normalizeForSpeech(input) {
  let t = String(input == null ? '' : input);

  for (const [re, to] of SYMBOLS) t = t.replace(re, to);

  // Разделители разрядов: «1 234 567» и «1,234,567» → одно число.
  t = t.replace(/(\d)[  ](?=\d{3}\b)/g, '$1');
  t = t.replace(/(\d),(?=\d{3}\b)/g, '$1');

  // Дробное словами: 3.5 → «три точка пять» (без «целых/десятых»: короче и не врёт про разряд).
  const fracWords = (num) => {
    const [a, b] = String(num).split(/[.,]/);
    return b === undefined ? numberToWords(a) : `${numberToWords(a)} точка ${numberToWords(b)}`;
  };

  // Единицы измерения и проценты идут ПЕРВЫМИ и умеют дробное число: иначе «1.4 МБ» распадалось
  // на «один» и «четыре мегабайта», а точка между ними оставалась немой.
  const unitKeys = Object.keys(UNITS).sort((a, b) => b.length - a.length).map((u) => u.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
  // Дробное число всегда требует родительного единственного: «1,4 мегабайта», «99,5 процента».
  const formFor = (num, forms) => (/[.,]/.test(String(num)) ? forms[1] : plural(parseInt(String(num), 10), forms[0], forms[1], forms[2]));
  t = t.replace(new RegExp(`(\\d+(?:[.,]\\d+)?)\\s*(${unitKeys.join('|')})(?![А-Яа-яЁёA-Za-z])`, 'g'),
    (_m, n, unit) => `${fracWords(n)} ${formFor(n, UNITS[unit])}`);

  // Проценты — с согласованием: 1 процент / 2 процента / 5 процентов.
  t = t.replace(/(\d+(?:[.,]\d+)?)\s*%/g, (_m, n) => `${fracWords(n)} ${formFor(n, ['процент', 'процента', 'процентов'])}`);

  // Версии и номера из трёх и более частей: 1.1.192 → «один точка один точка сто девяносто два».
  t = t.replace(/\b\d+(?:\.\d+){2,}\b/g, (m) => m.split('.').map((p) => numberToWords(p)).join(' точка '));

  // Оставшиеся дробные.
  t = t.replace(/\b(\d+)[.,](\d+)\b/g, (_m, a, b) => `${numberToWords(a)} точка ${numberToWords(b)}`);

  // Время 12:30 → «двенадцать тридцать».
  t = t.replace(/\b(\d{1,2}):(\d{2})\b/g, (_m, h, mi) => `${numberToWords(h)} ${numberToWords(mi)}`);

  // Остальные целые числа. Длинные цепочки цифр (хэши, id) читаются по цифрам самим numberToWords.
  t = t.replace(/\d+/g, (m) => numberToWords(m));

  // Латиница — по словам (термин из словаря, аббревиатура по буквам или транслит).
  t = t.replace(/[A-Za-z]+/g, (w) => translitWord(w));

  return t.replace(/[ \t]{2,}/g, ' ').trim();
}

// Есть ли что произносить: движок падает на фразе без кириллицы, поэтому такие пропускаем.
function hasSpeakable(text) { return CYRILLIC.test(String(text == null ? '' : text)); }

module.exports = { normalizeForSpeech, hasSpeakable, numberToWords, plural };
